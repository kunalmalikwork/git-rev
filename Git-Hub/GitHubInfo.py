# git push : Uploads local repository content to a remote repository, allowing others to access and collaborate on the code. The command is typically followed by the name of the remote (e.g., `origin`) and the branch name (e.g., `main` or `master`).

# git pull : Fetches and integrates changes from a remote repository into the current branch, ensuring that the local repository is up to date with the latest changes made by other collaborators.

# git clone <url> : clones the repo 